       greatest(40, m.grant_score - y.delta),
       case when m.paid_min_score is null then null else greatest(30, m.paid_min_score - y.delta) end,
       m.grants_count,
       coalesce(m.grants_count, 50) * 4 + y.delta * 7
from public.university_majors m
